// Local mirror: a generated, read-only copy of the skills library written
// into the user-level folders each tool scans, so native `/skill`
// autocomplete works without committing a copy to any repo.
//
// Every mirrored skill folder carries a `.typecase-mirror` marker; the
// mirror only ever deletes or overwrites folders that have one. Files are
// written read-only (0444) — the source of truth stays the library.

import {
  chmodSync, cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, watch, writeFileSync,
} from "node:fs";
import path from "node:path";
import process from "node:process";

import { createFsLibrary } from "./library-fs.mjs";
import { home } from "./paths.mjs";

export const MIRROR_MARKER = ".typecase-mirror";

export function mirrorTargets() {
  const h = home();
  return [
    { tool: "grok", dir: path.join(process.env.GROK_HOME ?? path.join(h, ".grok"), "skills") },
    { tool: "cursor", dir: path.join(h, ".cursor", "skills") },
    { tool: "claude", dir: path.join(h, ".claude", "skills") },
    { tool: "codex", dir: path.join(process.env.CODEX_HOME ?? path.join(h, ".codex"), "skills") },
  ];
}

function readMarker(dir) {
  try {
    return JSON.parse(readFileSync(path.join(dir, MIRROR_MARKER), "utf8"));
  } catch {
    return null;
  }
}

function chmodTree(dir, fileMode) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) chmodTree(full, fileMode);
    else chmodSync(full, fileMode);
  }
}

function removeMirrored(dir) {
  chmodTree(dir, 0o644);
  rmSync(dir, { recursive: true, force: true });
}

function contains(parent, child) {
  const rel = path.relative(parent, child);
  return rel === "" || (!rel.startsWith("..") && !path.isAbsolute(rel));
}

/**
 * Mirror every skill in `libraryDir` into the given targets (defaults to
 * all four tools' user-level skill folders). Idempotent; prunes mirrored
 * skills that left the library; never touches folders it did not generate.
 */
export async function writeMirror(libraryDir, { targets = mirrorTargets() } = {}) {
  const library = createFsLibrary(libraryDir);
  const skills = await library.list();
  const sourceRoot = path.resolve(libraryDir);
  const summary = { source: sourceRoot, skills: skills.length, written: 0, pruned: 0, skipped: [], targets: [] };

  for (const target of targets) {
    if (contains(target.dir, sourceRoot) || contains(sourceRoot, target.dir)) {
      summary.skipped.push({ target: target.dir, reason: "overlaps the library folder" });
      continue;
    }
    mkdirSync(target.dir, { recursive: true });
    const names = new Set(skills.map((s) => s.name));

    for (const s of skills) {
      const { dir: skillDir, version } = await library.read(s.name);
      const dest = path.join(target.dir, s.name);
      if (existsSync(dest) && !readMarker(dest)) {
        summary.skipped.push({ target: dest, reason: "exists and was not generated by typecase" });
        continue;
      }
      if (existsSync(dest)) removeMirrored(dest);
      cpSync(skillDir, dest, { recursive: true });
      chmodTree(dest, 0o444);
      writeFileSync(path.join(dest, MIRROR_MARKER), JSON.stringify({
        generatedBy: "typecase mirror",
        source: skillDir,
        version: version ?? null,
        generatedAt: new Date().toISOString(),
        note: "Generated read-only copy. Edit the source library, not this folder. Do not commit.",
      }, null, 2) + "\n", { mode: 0o444 });
      summary.written++;
    }

    for (const entry of readdirSync(target.dir, { withFileTypes: true })) {
      if (!entry.isDirectory() || names.has(entry.name)) continue;
      const dir = path.join(target.dir, entry.name);
      const marker = readMarker(dir);
      if (marker?.generatedBy === "typecase mirror" && contains(sourceRoot, marker.source ?? "")) {
        removeMirrored(dir);
        summary.pruned++;
      }
    }
    summary.targets.push(target.dir);
  }
  return summary;
}

/** Remove every typecase-generated skill folder from the targets. */
export function removeMirror({ targets = mirrorTargets() } = {}) {
  const summary = { removed: 0 };
  for (const target of targets) {
    if (!existsSync(target.dir)) continue;
    for (const entry of readdirSync(target.dir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue;
      const dir = path.join(target.dir, entry.name);
      if (readMarker(dir)?.generatedBy === "typecase mirror") {
        removeMirrored(dir);
        summary.removed++;
      }
    }
  }
  return summary;
}

/** Mirror now, then re-mirror whenever the library folder changes (debounced). */
export function watchMirror(libraryDir, { targets = mirrorTargets(), onUpdate = () => {} } = {}) {
  let timer = null;
  const run = () => writeMirror(libraryDir, { targets }).then(onUpdate, (err) => onUpdate({ error: String(err?.message ?? err) }));
  run();
  return watch(libraryDir, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(run, 500);
  });
}
